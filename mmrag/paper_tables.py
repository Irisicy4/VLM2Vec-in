#!/usr/bin/env python3
"""Emit LaTeX table bodies for the paper straight from the per-seed result json.

Rationale: the headline table previously mixed estimators ACROSS ITS OWN COLUMNS — accuracy from a
3-seed per-seed-best-checkpoint mean, retrieval from an unrelated single-seed run — which
manufactured a retrieval margin that does not exist. Generating every column of a row from one
declared list of per-seed files makes that class of error impossible to reintroduce by hand.

Usage:  python3 mmrag/paper_tables.py [main|evqa|contrast]
"""
import json, os, math, sys

R = os.environ.get("MMRAG_DATA", "/raid/icy/mmrag_data") + "/results"
TCRIT = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365, 8: 2.306}

def read(stem):
    rp, vp = f"{R}/{stem}.retrieval.metrics.json", f"{R}/{stem}.vqa_top5.json"
    if not os.path.exists(rp):
        return None
    r = json.load(open(rp))
    o = {"entR@1": r["entity_recall"]["1"]*100, "entR@5": r["entity_recall"]["5"]*100,
         "entR@10": r["entity_recall"]["10"]*100, "ansR@5": r["answer_recall"]["5"]*100}
    if os.path.exists(vp):
        v = json.load(open(vp))
        o.update(acc=v["acc"]*100, strictEM=v.get("strict_em", float("nan"))*100,
                 f1=v.get("f1", float("nan"))*100)
    return o

def agg(stems, keys):
    rows = [v for s in stems if (v := read(s))]
    out = {}
    for k in keys:
        xs = [r[k] for r in rows if k in r and r[k] == r[k]]
        if not xs:
            out[k] = (None, None, 0, []); continue
        n = len(xs); mu = sum(xs)/n
        sd = math.sqrt(sum((x-mu)**2 for x in xs)/(n-1)) if n > 1 else None
        out[k] = (mu, sd, n, xs)
    return out

def cell(t, bold=False):
    mu, sd, n, _ = t
    if mu is None: return "---"
    s = f"{mu:.2f}" if sd is None else f"{mu:.2f} \\pm {sd:.2f}"
    return ("$\\mathbf{" + s.replace("\\pm", "}\\pm\\mathbf{") + "}$") if bold else f"${s}$"

KEYS = ["acc", "strictEM", "f1", "entR@1", "entR@5", "entR@10", "ansR@5"]

MAIN = [
 ("zero-shot base", ["gme2b-zeroshot-3k-repro"], "no training; 1 seed"),
 ("relevance-SFT (per-seed best ckpt)",
  ["sft-curve-ck750", "sft-curve-lr1e4-s1-ck1050", "sft-curve-lr1e4-s2-ck1050"],
  "acc-argmax within each seed over ck450--1200; ALL columns read at that checkpoint"),
 ("v2 PL-GRPO $+$ anchor",
  ["plgrpo-gme2b-nogold", "plgrpo-gme2b-nogold-s1", "plgrpo-s2", "plgrpo-s3"],
  "endpoint; all 4 seeds on disk"),
 ("v3-pure", ["v3-pure", "v3-pure-s1", "v3-pure-s2"], "endpoint = checkpoint max on all 3 seeds"),
]
EVQA = [
 ("zero-shot base", ["evqa-zeroshot"], ""),
 ("relevance-SFT", ["evqa-sft-ck750"], ""),
 ("v3-pure", ["evqa-v3pure", "evqa-v3pure-s1", "evqa-v3pure-s2"], "3 seeds"),
]

def emit(spec, title):
    print(f"% ==== {title} — generated by mmrag/paper_tables.py, do not hand-edit ====")
    for name, stems, note in spec:
        a = agg(stems, KEYS)
        got = [s for s in stems if read(s)]
        miss = [s for s in stems if not read(s)]
        cells = " & ".join(cell(a[k]) for k in KEYS)
        print(f"{name:38s} & {cells} \\\\   % n={len(got)} {note}")
        if miss: print(f"%   NOT ON DISK: {', '.join(miss)}")
    print()

def contrast(a_stems, b_stems, label):
    A, B = agg(a_stems, KEYS), agg(b_stems, KEYS)
    print(f"=== {label} ===")
    for k in KEYS:
        (ma, sa, na, xa), (mb, sb, nb, xb) = A[k], B[k]
        if ma is None or mb is None: continue
        d = ma - mb
        if not sa or not sb or na < 2 or nb < 2:
            print(f"  {k:8s} {d:+6.2f}   (a leg has 1 seed — no interval)"); continue
        sp = math.sqrt(((na-1)*sa*sa + (nb-1)*sb*sb)/(na+nb-2))
        half_s = TCRIT[na+nb-2]*sp*math.sqrt(1/na+1/nb)
        se_w = math.sqrt(sa*sa/na + sb*sb/nb)
        dofw = (sa*sa/na+sb*sb/nb)**2/((sa*sa/na)**2/(na-1)+(sb*sb/nb)**2/(nb-1))
        half_w = TCRIT.get(int(round(dofw)), 2.0)*se_w
        sep = "COMPLETE SEPARATION" if min(xa) > max(xb) or max(xa) < min(xb) else "overlapping"
        v = "callable" if abs(d) > half_s and abs(d) > half_w else (
            "Student only" if abs(d) > half_s else "NOT callable")
        print(f"  {k:8s} {d:+6.2f}  Student[{d-half_s:+.2f},{d+half_s:+.2f}] "
              f"Welch[{d-half_w:+.2f},{d+half_w:+.2f}] dof{dofw:.1f}  {v}  {sep}")
    print()

what = sys.argv[1] if len(sys.argv) > 1 else "main"
if what in ("main", "all"):
    print("% columns: acc & strictEM & F1 & entR@1 & entR@5 & entR@10 & ansR@5")
    emit(MAIN, "InfoSeek main arms")
if what in ("evqa", "all"):
    emit(EVQA, "E-VQA out of domain")
if what in ("contrast", "all"):
    sft = MAIN[1][1]
    contrast(MAIN[3][1], sft, "v3-pure MINUS relevance-SFT")
    contrast(MAIN[2][1], sft, "v2 anchored MINUS relevance-SFT")
    contrast(MAIN[3][1], MAIN[2][1], "v3-pure MINUS v2 anchored")
